export const eventById = (id, opts) => {
  if (opts && opts.byTenant != null){
    const want = !!opts.byTenant;
    const hit = EVENTS.find(e => e.id === id && !!e.byTenant === want);
    if (hit) return hit;
  }
  return EVENTS.find(e => e.id === id);
};

