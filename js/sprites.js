// sprites.js — 乘客的像素圖。每個 7×9 格，兩種姿勢：normal 與 urgent。
//   '#' = 身體（顏色由主題決定：深色主題用淺色墨、亮色主題用深色墨）
//   'o' = 配件（每種乘客自己的顏色，這就是它的識別色）
//   '.' = 透明
// urgent 是「快沒耐性」的姿勢：手舉起來、腳張開，身體整個轉成警示色。
// 剪影要在 14×18 px 的大小下就分得出來，所以每種人的外形差異放在
// 「輪廓」上（貓是矮寬的四腳、幽靈沒有腳、搬家公司抱著一個大箱子），
// 而不是只靠配件的顏色。
//
// ---- 配件色的三條判準（#37，全部用 CIEDE2000，不是等號也不是對比度）----
// 1. 兩兩之間 ΔE ≥ 12
// 2. 對三種身體色（pal.ink 樓層／pal.inkCar 轎廂／pal.bad urgent）ΔE ≥ 25
// 3. 色相相對原設計位移 ≤ 21°（貓要留在橘色、嬰兒車要留在淺藍）
//
// **第 1 條為什麼是 12 而不是 25**：25 在幾何上做不到。26 個顏色若同時要求
// 「彼此 ≥ 25」與「離三種身體色都 ≥ 25」，實測（全色域最遠點取樣）兩兩間距的
// 上限只有 **≈ 19**；即使把身體門檻放寬到 15，上限也只有 20.6。
// 而把門檻推到 18 是做得到的，代價是 **21/26 的顏色要改，而且會毀掉語意**——
// 實測那個解把貓從橘色變成米色、爆米花從奶油色變成橄欖綠、嬰兒車從淺藍變成深綠。
// 所以這裡選「修好真正的缺陷、保住色相」：12 以下的近似重複與所有身體色衝突全部
// 消掉（改動前有 16 對 < 12、7 個身體衝突；現在都是 0），而 12～18 之間的配對
// 留著，靠剪影分辨——**檔頭第一段本來就說識別主要靠輪廓**。
// 門檻要往上調是設計決定，不是這個檔案可以自己決定的。

